/** Repack existing authored poses into standard Codex v1 packs. No runtime legacy adapter. */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { DESKTOP_PET_BUILTINS, DESKTOP_PET_CONTRACT as C } from "@drora/shared";
import { codexPetTracks } from "../src/shared/desktopPetAnimation.js";

const assets = fileURLToPath(new URL("../assets/", import.meta.url));
const output = process.argv[2] ?? join(assets, "desktop-pets");
const modulePath =
  process.argv[3] ??
  fileURLToPath(new URL("../src/main/desktopPetBuiltinPacks.ts", import.meta.url));
const violet = JSON.parse(await readFile(join(assets, "desktop-pet/motion-manifest.json"), "utf8"));
const catgirls = JSON.parse(
  await readFile(join(assets, "desktop-pet-catgirls/manifest.json"), "utf8"),
);
const violetAtlas = await readFile(join(assets, "desktop-pet/violet-cat-motion-atlas.webp"));
const tracks = codexPetTracks();
const sourceNames = {
  violet: [
    "idle",
    "working",
    "working",
    "attention",
    "completed",
    "error",
    "attention",
    "working",
    "completed",
  ],
  catgirl: ["idle", "walk", "walk", "wave", "happy", "error", "attention", "working", "happy"],
};
const packed = [];
for (const builtin of DESKTOP_PET_BUILTINS) {
  const character = catgirls.characters.find((entry) => entry.id === builtin.id);
  if (builtin.id !== "violet" && !character) throw new Error(`Missing authored pet: ${builtin.id}`);
  const images = [];
  for (const track of tracks) {
    const row = track.frames[0].row;
    const count = track.state === "idle" ? track.frames.length : track.loopStart / 3;
    const sourceName = sourceNames[builtin.id === "violet" ? "violet" : "catgirl"][row];
    const sourceRow = violet.rows.findIndex((entry) => entry.mode === sourceName);
    const action = character?.actions.find((entry) => entry.id === sourceName);
    const sourceCount = character ? action?.frameCount : violet.rows[sourceRow]?.frames.length;
    if (!sourceCount) throw new Error(`Missing source motion ${builtin.id}/${sourceName}`);
    const atlas = character
      ? await readFile(join(assets, "desktop-pet-catgirls", action.atlas))
      : violetAtlas;
    for (let frame = 0; frame < count; frame++) {
      const index = Math.floor((frame * sourceCount) / count);
      let cell;
      if (character) {
        cell = sharp(atlas)
          .extract({
            left: (index % catgirls.columns) * catgirls.frameWidth,
            top: Math.floor(index / catgirls.columns) * catgirls.frameHeight,
            width: catgirls.frameWidth,
            height: catgirls.frameHeight,
          })
          .resize(192, 208, { fit: "contain", background: "#0000" });
      } else {
        cell = sharp(atlas)
          .extract({
            left: index * violet.cellSize,
            top: sourceRow * violet.cellSize,
            width: violet.cellSize,
            height: violet.cellSize,
          })
          .extend({ top: 8, bottom: 8, left: 0, right: 0, background: "#0000" });
      }
      // 素材迁移只重排/等比装框；左行走镜像右行走，不在运行时保留旧动作映射。
      if (track.state === "running-left") cell = cell.flop();
      images.push({ input: await cell.png().toBuffer(), left: frame * 192, top: row * 208 });
    }
  }
  const bytes = await sharp({
    create: { width: 1536, height: 1872, channels: 4, background: "#0000" },
  })
    .composite(images)
    .webp({ quality: 88, alphaQuality: 100, effort: 6 })
    .toBuffer();
  const manifest = {
    id: builtin.id,
    displayName: builtin.nameEn,
    description: null,
    spriteVersionNumber: 1,
    spritesheetPath: C.spritesheet,
  };
  const directory = join(output, builtin.id);
  await mkdir(directory, { recursive: true });
  await writeFile(join(directory, C.manifest), JSON.stringify(manifest, null, 2) + "\n");
  await writeFile(join(directory, C.spritesheet), bytes);
  packed.push({ id: builtin.id, manifest, base64: bytes.toString("base64") });
  console.log(`${builtin.id}: Codex v1 1536x1872, ${Math.round(bytes.length / 1024)} KiB`);
}
await mkdir(dirname(modulePath), { recursive: true });
await writeFile(
  modulePath,
  `/** Generated by scripts/generate-codex-pet-builtins.mjs from standard assets/desktop-pets packs. */\nimport type { DesktopPetManifest } from "@drora/shared";\n\nexport const desktopPetBuiltinPacks: readonly { id: string; manifest: DesktopPetManifest; base64: string }[] = ${JSON.stringify(packed, null, 2)};\n`,
);
